def _matches(product_name: str, key: str, knowledge: dict[str, Any]) -> bool:
    normalized = product_name.replace(" ", "").lower()
    candidates = [key, *knowledge.get("aliases", [])]

    return any(
        str(candidate).replace(" ", "").lower() in normalized
        for candidate in candidates
        if candidate
    )


def find_product_knowledge(product_name: str) -> dict[str, Any]:
    """상품명과 가장 잘 맞는 지식을 반환합니다.

    일치 상품이 없으면 DEFAULT_KNOWLEDGE를 반환하므로
    SectionWriter에서 별도 예외 처리 없이 사용할 수 있습니다.
    """
    name = str(product_name or "상품").strip()

    for key, knowledge in PRODUCT_KNOWLEDGE.items():
        if _matches(name, key, knowledge):
            result = deepcopy(DEFAULT_KNOWLEDGE)
            result.update(deepcopy(knowledge))
            result["knowledge_key"] = key
            result["product_name"] = name
            return result

    result = deepcopy(DEFAULT_KNOWLEDGE)
    result["knowledge_key"] = "default"
    result["product_name"] = name
    return result